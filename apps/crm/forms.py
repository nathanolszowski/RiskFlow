"""Forms of the crm app: company and contact."""

from typing import Any

from core.forms import enable_address_autocomplete
from django import forms

from .models import Company, Contact


class CompanyForm(forms.ModelForm):
    """Create or edit a company.

    Optional fields are declared as not required, and every widget gets the
    ``form-input`` class and an example placeholder. The reference is read-only: it is
    generated by ``Company.save()``. The Sirene data that is not typed by hand (state,
    head office, NAF 2025 activity) is not part of the form.
    """

    reference = forms.CharField(required=False)  # read-only, see __init__
    vat_number = forms.CharField(required=False)
    legal_structure = forms.CharField(required=False)
    nb_employees = forms.IntegerField(required=False)
    labels = forms.CharField(widget=forms.Textarea(attrs={"rows": 2}), required=False)
    executive_board = forms.CharField(
        widget=forms.Textarea(attrs={"rows": 2}), required=False
    )
    website = forms.URLField(required=False)

    class Meta:
        model = Company
        fields = [
            "reference",
            "name",
            "siren",
            "siret",
            "vat_number",
            "business_line",
            "legal_structure",
            "company_size_category",
            "nb_employees",
            "creation_date",
            "website",
            "address_line",
            "postal_code",
            "city",
            "labels",
            "executive_board",
        ]
        widgets = {
            "creation_date": forms.DateInput(attrs={"type": "date"}, format="%Y-%m-%d"),
            "labels": forms.Textarea(attrs={"rows": 2}),
            "executive_board": forms.Textarea(attrs={"rows": 2}),
        }

    def __init__(self, *args: Any, **kwargs: Any) -> None:
        """Style the widgets, make the reference read-only and set the placeholders.

        Args:
            *args: Positional arguments passed to ``ModelForm``.
            **kwargs: Keyword arguments passed to ``ModelForm``.
        """
        super().__init__(*args, **kwargs)

        for field in self.fields.values():
            field.widget.attrs["class"] = "form-input"

        # The address was mandatory when it was a single text field
        for name in ("address_line", "postal_code", "city"):
            self.fields[name].required = True
        enable_address_autocomplete(self)

        # Read-only: generated by Company.save(), shown when editing but never taken from
        # the request (a disabled field keeps the instance value, whatever is posted)
        reference_field = self.fields["reference"]
        reference_field.disabled = True
        reference_field.widget.attrs["class"] = "form-input-readonly"

        placeholders = {
            "name": "ex: ACME Industries",
            "siren": "ex: 775652126",
            "siret": "ex: 77565212602114",
            "vat_number": "ex: FR12775652126",
            "legal_structure": "ex: SAS, SARL...",
            "business_line": "ex: Industrie métallurgique",
            "company_size_category": "ex: PME / ETI / GE",
            "nb_employees": "ex: 50",
            "creation_date": "ex: 2015-06-12",
            "website": "ex: https://www.exemple.fr",
            "address_line": "ex: 12 Rue de la Paix",
            "postal_code": "ex: 75002",
            "city": "ex: Paris",
            "labels": "ex: ISO 9001, ISO 27001",
            "executive_board": "ex: Jean Dupont (PDG)",
        }
        for field_name, placeholder_text in placeholders.items():
            field = self.fields.get(field_name)
            if field:
                field.widget.attrs["placeholder"] = placeholder_text


class ContactForm(forms.ModelForm):
    """Create or edit a contact.

    Optional fields are declared as not required, and every widget gets the
    ``form-input`` class and an example placeholder.
    """

    email = forms.EmailField(required=False)
    phone_number_fix = forms.CharField(required=False)
    phone_number_mobile = forms.CharField(required=False)

    class Meta:
        model = Contact
        fields = [
            "company",
            "first_name",
            "last_name",
            "email",
            "phone_number_fix",
            "phone_number_mobile",
            "position",
        ]

    def __init__(self, *args: Any, **kwargs: Any) -> None:
        """Style the widgets, set the company empty label and the placeholders.

        Every company can be chosen: companies are shared between users.

        Args:
            *args: Positional arguments passed to ``ModelForm``.
            **kwargs: Keyword arguments passed to ``ModelForm``.
        """
        super().__init__(*args, **kwargs)

        for name, field in self.fields.items():
            field.widget.attrs.update({"class": "form-input"})

        company_field = self.fields.get("company")
        if isinstance(company_field, forms.ModelChoiceField):
            company_field.empty_label = "Sélectionnez un client"
        # Placeholders
        placeholders = {
            "first_name": "ex: Jean",
            "last_name": "ex: Dupont",
            "email": "jean.dupont@exemple.fr",
            "phone_number_fix": "ex: 01 23 45 67 89",
            "phone_number_mobile": "ex: 06 12 34 56 78",
            "position": "ex: Responsable Achat",
        }
        for field_name, placeholder_text in placeholders.items():
            field = self.fields.get(field_name)
            if field:
                field.widget.attrs["placeholder"] = placeholder_text
